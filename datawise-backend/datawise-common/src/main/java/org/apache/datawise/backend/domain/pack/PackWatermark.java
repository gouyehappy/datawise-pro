package org.apache.datawise.backend.domain.pack;

/** Builds export / report watermark footers for trial or site-bound builds. */
public final class PackWatermark {

    public static final String DEFAULT_TRIAL_FOOTER = "Generated by DataWise Trial — unlock packs for production use.";

    private PackWatermark() {
    }

    /**
     * @param enabled         master switch
     * @param customText      optional override (blank → default trial text)
     * @param siteId          license site id when present
     * @param anyTrialActive  true when at least one pack is in trial
     * @param fullyLicensed   true when a non-trial license covers the site
     */
    public static String resolveFooter(
                                       boolean enabled,
                                       String customText,
                                       String siteId,
                                       boolean anyTrialActive,
                                       boolean fullyLicensed) {
        if (!enabled) {
            return null;
        }
        if (fullyLicensed && !anyTrialActive) {
            if (siteId != null && !siteId.isBlank()) {
                return "DataWise · site " + siteId.trim();
            }
            return null;
        }
        String base = customText != null && !customText.isBlank()
                ? customText.trim()
                : DEFAULT_TRIAL_FOOTER;
        if (siteId != null && !siteId.isBlank()) {
            return base + " [" + siteId.trim() + "]";
        }
        return base;
    }

    public static String appendToText(String content, String footer) {
        if (footer == null || footer.isBlank()) {
            return content;
        }
        String body = content != null ? content : "";
        if (body.isEmpty()) {
            return "-- " + footer;
        }
        String sep = body.endsWith("\n") ? "" : "\n";
        return body + sep + "-- " + footer + "\n";
    }
}
