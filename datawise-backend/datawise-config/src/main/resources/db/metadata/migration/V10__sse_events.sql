-- Shared SSE pub/sub event log (multi-instance fan-out via JDBC polling)
CREATE TABLE dw_sse_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel VARCHAR(512) NOT NULL,
    event_name VARCHAR(128) NOT NULL,
    payload_json CLOB NOT NULL,
    origin_instance_id VARCHAR(256) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_dw_sse_events_created ON dw_sse_events (created_at);
