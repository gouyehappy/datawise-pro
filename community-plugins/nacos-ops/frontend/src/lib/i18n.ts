export type LocaleDict = typeof en

export function createI18n(locale: string) {
  const dict = /^zh/i.test(locale) ? zh : en
  return (key: keyof LocaleDict, vars?: Record<string, string | number>) => {
    let s = dict[key] || en[key] || String(key)
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
      }
    }
    return s
  }
}
