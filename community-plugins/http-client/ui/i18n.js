  let locale = "zh-CN";

  function normalize(value) {
    if (!value) return "zh-CN";
    const lower = String(value).toLowerCase();
    if (lower.startsWith("zh")) return "zh-CN";
    return "en";
  }

  function setLocale(value) {
    locale = normalize(value);
    return locale;
  }

  function interpolate(text, params) {
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, (match, key) =>
      Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match);
  }

  function t(key, params) {
    const table = dictionaries[locale] || dictionaries["zh-CN"];
    const text = table[key] !== undefined ? table[key] : dictionaries["zh-CN"][key];
    return text === undefined ? key : interpolate(text, params);
  }

  // Apply translated labels to static HTML before the first paint. The host
  // locale arrives asynchronously, so app.js re-runs this after the handshake.
  function applyStaticLabels() {
    if (typeof document === "undefined") return;
    document.documentElement.lang = locale;
    document.querySelectorAll("[data-i18n]").forEach((node) => {
      node.textContent = t(node.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-title]").forEach((node) => {
      node.title = t(node.dataset.i18nTitle);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
      node.placeholder = t(node.dataset.i18nPlaceholder);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
      node.setAttribute("aria-label", t(node.dataset.i18nAria));
    });
  }

  window.HC = window.HC || {};
  window.HC.i18n = { t, setLocale, applyStaticLabels, get locale() { return locale; }, dictionaries };
  applyStaticLabels();
