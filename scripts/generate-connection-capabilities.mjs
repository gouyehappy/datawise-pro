#!/usr/bin/env node
/**
 * Generate connection product-capability matrix from
 * datawise-backend/datawise-connectors/capabilities/*.json
 *
 * Usage:
 *   node scripts/generate-connection-capabilities.mjs
 *   node scripts/generate-connection-capabilities.mjs --check
 */
import fs from 'node:fs'
import path from 'node:path'
import {fileURLToPath} from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')
const sourceDir = path.join(root, 'datawise-backend', 'datawise-connectors', 'capabilities')
const feOut = path.join(
    root,
    'datawise-frontend',
    'src',
    'shared',
    'capabilities',
    'generated',
    'connection-capability-matrix.ts',
)
const beOut = path.join(
    root,
    'datawise-backend',
    'datawise-connectors',
    'datawise-connector-spi',
    'src',
    'main',
    'resources',
    'connection-capability-matrix.json',
)
const cliTxnOut = path.join(
    root,
    'headless-cli',
    'src',
    'generated',
    'transactional-ddl-types.json',
)

const checkOnly = process.argv.includes('--check')

function readJson(filePath) {
    const text = fs.readFileSync(filePath, 'utf8').replace(/^\uFEFF/, '')
    return JSON.parse(text)
}

function fail(message) {
    console.error(`[generate-connection-capabilities] ${message}`)
    process.exit(1)
}

function mergeFeatures(base, overlay, allowed) {
    const out = {}
    for (const key of allowed) {
        out[key] = false
    }
    if (base) {
        for (const [k, v] of Object.entries(base)) {
            if (!allowed.includes(k)) fail(`unknown feature in family: ${k}`)
            out[k] = Boolean(v)
        }
    }
    if (overlay) {
        for (const [k, v] of Object.entries(overlay)) {
            if (!allowed.includes(k)) fail(`unknown feature in type: ${k}`)
            out[k] = Boolean(v)
        }
    }
    return out
}

function loadMatrix() {
    const schema = readJson(path.join(sourceDir, '_schema.json'))
    const allowedFeatures = schema.features
    const supportLevels = new Set(schema.supportLevels)
    const formKinds = new Set(schema.formKinds)

    const familiesDir = path.join(sourceDir, '_families')
    const families = {}
    for (const name of fs.readdirSync(familiesDir).filter((n) => n.endsWith('.json'))) {
        const fam = readJson(path.join(familiesDir, name))
        if (!fam.id) fail(`family ${name} missing id`)
        if (!supportLevels.has(fam.supportLevel)) fail(`family ${fam.id}: bad supportLevel`)
        if (!formKinds.has(fam.formKind)) fail(`family ${fam.id}: bad formKind`)
        families[fam.id] = fam
    }

    const entries = {}
    for (const name of fs.readdirSync(sourceDir).filter((n) => n.endsWith('.json') && !n.startsWith('_'))) {
        const raw = readJson(path.join(sourceDir, name))
        const dbType = raw.dbType
        if (!dbType) fail(`${name}: missing dbType`)
        if (`${dbType}.json` !== name) fail(`${name}: filename must be {dbType}.json`)

        let supportLevel = raw.supportLevel
        let specializedSurface = raw.specializedSurface
        let formKind = raw.formKind
        let featureBase = null

        if (raw.extends) {
            const fam = families[raw.extends]
            if (!fam) fail(`${dbType}: unknown extends "${raw.extends}"`)
            supportLevel = supportLevel ?? fam.supportLevel
            specializedSurface = specializedSurface ?? fam.specializedSurface
            formKind = formKind ?? fam.formKind
            featureBase = fam.features
        }

        supportLevel = supportLevel ?? 'browse'
        specializedSurface = Boolean(specializedSurface)
        formKind = formKind ?? 'other'

        if (!supportLevels.has(supportLevel)) fail(`${dbType}: bad supportLevel`)
        if (!formKinds.has(formKind)) fail(`${dbType}: bad formKind`)

        entries[dbType] = {
            dbType,
            supportLevel,
            specializedSurface,
            formKind,
            features: mergeFeatures(featureBase, raw.features, allowedFeatures),
        }
    }

    return {
        schemaVersion: 1,
        generatedAt: new Date().toISOString().slice(0, 10),
        featureKeys: allowedFeatures,
        supportLevels: schema.supportLevels,
        formKinds: schema.formKinds,
        types: entries,
    }
}

function renderTs(matrix) {
    const featureUnion = matrix.featureKeys.map((k) => `  | '${k}'`).join('\n')
    const body = JSON.stringify(matrix, null, 2)
    return `/* eslint-disable */
/**
 * AUTO-GENERATED by scripts/generate-connection-capabilities.mjs — do not edit.
 * Source: datawise-backend/datawise-connectors/capabilities/
 */
export type ConnectionProductFeature =
${featureUnion}

export type ConnectionSupportLevel = ${matrix.supportLevels.map((s) => `'${s}'`).join(' | ')}
export type ConnectionFormKind = ${matrix.formKinds.map((s) => `'${s}'`).join(' | ')}

export interface ConnectionCapabilityProfile {
  dbType: string
  supportLevel: ConnectionSupportLevel
  specializedSurface: boolean
  formKind: ConnectionFormKind
  features: Record<ConnectionProductFeature, boolean>
}

export interface ConnectionCapabilityMatrix {
  schemaVersion: number
  generatedAt: string
  featureKeys: ConnectionProductFeature[]
  supportLevels: ConnectionSupportLevel[]
  formKinds: ConnectionFormKind[]
  types: Record<string, ConnectionCapabilityProfile>
}

export const CONNECTION_CAPABILITY_MATRIX: ConnectionCapabilityMatrix = ${body} as const
`
}

function writeOrCheck(filePath, content) {
    const normalized = content.replace(/\r\n/g, '\n')
    if (checkOnly) {
        if (!fs.existsSync(filePath)) {
            fail(`missing generated file: ${path.relative(root, filePath)} (run generate without --check)`)
        }
        const existing = fs.readFileSync(filePath, 'utf8').replace(/\r\n/g, '\n')
        // Ignore generatedAt drift in check by comparing structural JSON for BE; for TS strip date line.
        const stripDate = (s) => s.replace(/"generatedAt":\s*"[^"]+"/, '"generatedAt": "<date>"')
        if (stripDate(existing) !== stripDate(normalized)) {
            fail(`stale generated file: ${path.relative(root, filePath)}`)
        }
        return
    }
    fs.mkdirSync(path.dirname(filePath), {recursive: true})
    fs.writeFileSync(filePath, normalized, 'utf8')
    console.log(`wrote ${path.relative(root, filePath)}`)
}

const matrix = loadMatrix()
assertDbTypeSourcesAligned(matrix)
writeOrCheck(feOut, renderTs(matrix))
writeOrCheck(beOut, `${JSON.stringify(matrix, null, 2)}\n`)
const txnTypes = Object.values(matrix.types)
    .filter((profile) => profile.features?.transactionalDdl)
    .map((profile) => profile.dbType)
    .sort()
writeOrCheck(
    cliTxnOut,
    `${JSON.stringify({generatedAt: matrix.generatedAt, types: txnTypes}, null, 2)}\n`,
)
if (checkOnly) {
    console.log('[generate-connection-capabilities] ok')
}

/**
 * Cross-check DbType.java enum + db-type-profiles.properties + matrix types (+ _aliases.json).
 * Canonical enum ids must appear in profiles and matrix; alias keys must resolve to an enum id.
 */
function assertDbTypeSourcesAligned(matrix) {
    const dbTypeJava = path.join(
        root,
        'datawise-backend',
        'datawise-connectors',
        'datawise-connector-spi',
        'src',
        'main',
        'java',
        'org',
        'apache',
        'datawise',
        'backend',
        'common',
        'DbType.java',
    )
    const profilesPath = path.join(
        root,
        'datawise-backend',
        'datawise-connectors',
        'datawise-connector-spi',
        'src',
        'main',
        'resources',
        'db-type-profiles.properties',
    )
    const aliasesPath = path.join(sourceDir, '_aliases.json')

    const javaSrc = fs.readFileSync(dbTypeJava, 'utf8')
    const enumIds = [...javaSrc.matchAll(/^\s+([A-Z][A-Z0-9_]+)\s*(?:,|;)/gm)].map((m) =>
        m[1].toLowerCase(),
    )
    if (enumIds.length < 10) fail(`failed to parse DbType enum from ${path.relative(root, dbTypeJava)}`)

    const propsSrc = fs.readFileSync(profilesPath, 'utf8')
    const profileIds = [...new Set([...propsSrc.matchAll(/^([a-z0-9_]+)\./gm)].map((m) => m[1]))]

    const aliasesDoc = readJson(aliasesPath)
    const aliases = aliasesDoc.aliases || {}
    const matrixIds = Object.keys(matrix.types || {})

    const enumSet = new Set(enumIds)
    const profileSet = new Set(profileIds)
    const matrixSet = new Set(matrixIds)

    const enumMissingProfile = enumIds.filter((id) => !profileSet.has(id))
    if (enumMissingProfile.length) {
        fail(`DbType enum missing db-type-profiles.properties entries: ${enumMissingProfile.join(', ')}`)
    }
    const profileMissingEnum = profileIds.filter((id) => !enumSet.has(id))
    if (profileMissingEnum.length) {
        fail(`db-type-profiles.properties keys not in DbType enum: ${profileMissingEnum.join(', ')}`)
    }

    const enumMissingMatrix = enumIds.filter((id) => !matrixSet.has(id))
    if (enumMissingMatrix.length) {
        fail(
            `DbType enum missing connection-capability matrix types (use canonical ids, not aliases): ${enumMissingMatrix.join(', ')}`,
        )
    }

    for (const [alias, canonical] of Object.entries(aliases)) {
        if (!enumSet.has(canonical)) {
            fail(`_aliases.json: ${alias} → ${canonical} but ${canonical} is not a DbType enum id`)
        }
        if (matrixSet.has(alias) && alias !== canonical) {
            fail(
                `matrix must not use alias id "${alias}" as a type key; use canonical "${canonical}" (see capabilities/_aliases.json)`,
            )
        }
    }

    const matrixMissingEnum = matrixIds.filter((id) => !enumSet.has(id) && !aliases[id])
    if (matrixMissingEnum.length) {
        fail(`matrix types not in DbType enum or _aliases.json: ${matrixMissingEnum.join(', ')}`)
    }

    console.log(
        `[generate-connection-capabilities] dbType sources aligned: enum=${enumIds.length} profiles=${profileIds.length} matrix=${matrixIds.length} aliases=${Object.keys(aliases).length}`,
    )
}
